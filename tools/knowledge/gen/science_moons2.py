#!/usr/bin/env python3
"""Writes data/science/gen_moons2.txt: size and discovery of the best-known moons.

Data sources: NASA/JPL Solar System Dynamics planetary satellite physical parameters
(https://ssd.jpl.nasa.gov/sats/phys_par/, public domain) for mean diameters, and NASA
Science moon pages for who discovered each moon and when. Hand-checked; moons whose size is
poorly known were left out.

Run from the repo root:  python3 tools/knowledge/gen/science_moons2.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "data", "science", "gen_moons2.txt"))
OUR_MOON = 3475

# name, planet, mean diameter km, discoverer, year, note
MOONS = [
    ("Io", "Jupiter", 3643, "Galileo Galilei", 1610, None),
    ("Europa", "Jupiter", 3122, "Galileo Galilei", 1610, None),
    ("Ganymede", "Jupiter", 5268, "Galileo Galilei", 1610, "It's the largest moon in the solar system, even bigger than the planet Mercury."),
    ("Callisto", "Jupiter", 4821, "Galileo Galilei", 1610, None),
    ("Amalthea", "Jupiter", 167, "Edward Emerson Barnard", 1892, "It was the last moon discovered by eye at a telescope, without photography."),
    ("Titan", "Saturn", 5150, "Christiaan Huygens", 1655, "It's bigger than the planet Mercury."),
    ("Rhea", "Saturn", 1527, "Giovanni Cassini", 1672, None),
    ("Iapetus", "Saturn", 1469, "Giovanni Cassini", 1671, None),
    ("Dione", "Saturn", 1123, "Giovanni Cassini", 1684, None),
    ("Tethys", "Saturn", 1062, "Giovanni Cassini", 1684, None),
    ("Enceladus", "Saturn", 504, "William Herschel", 1789, None),
    ("Mimas", "Saturn", 396, "William Herschel", 1789, None),
    ("Phoebe", "Saturn", 213, "William Pickering", 1899, "It was the first moon discovered using photographs."),
    ("Titania", "Uranus", 1577, "William Herschel", 1787, "It's the largest moon of Uranus."),
    ("Oberon", "Uranus", 1523, "William Herschel", 1787, None),
    ("Umbriel", "Uranus", 1169, "William Lassell", 1851, None),
    ("Ariel", "Uranus", 1158, "William Lassell", 1851, None),
    ("Miranda", "Uranus", 472, "Gerard Kuiper", 1948, None),
    ("Triton", "Neptune", 2707, "William Lassell", 1846, "He found it just 17 days after Neptune itself was discovered."),
    ("Proteus", "Neptune", 420, "the Voyager 2 team", 1989, "It's dark and lumpy, about as big as an object can be before gravity pulls it round."),
    ("Charon", "Pluto", 1212, "James Christy", 1978, "It's about half as wide as Pluto."),
    ("Phobos", "Mars", 22, "Asaph Hall", 1877, None),
    ("Deimos", "Mars", 12, "Asaph Hall", 1877, None),
]


# orbital period in Earth days (NASA/JPL mean orbital elements); True if it orbits backwards
ORBIT = {
    "Io": (1.769, False), "Europa": (3.551, False), "Ganymede": (7.155, False), "Callisto": (16.689, False),
    "Amalthea": (0.498, False), "Titan": (15.945, False), "Rhea": (4.518, False), "Iapetus": (79.33, False),
    "Dione": (2.737, False), "Tethys": (1.888, False), "Enceladus": (1.370, False), "Mimas": (0.942, False),
    "Phoebe": (550.3, True), "Titania": (8.706, False), "Oberon": (13.463, False), "Umbriel": (4.144, False),
    "Ariel": (2.520, False), "Miranda": (1.413, False), "Triton": (5.877, True), "Proteus": (1.122, False),
    "Charon": (6.387, False), "Phobos": (0.319, False), "Deimos": (1.262, False),
}


def period_text(days):
    if days < 2:
        h = days * 24
        return f"{h:.1f} hours" if h < 10 else f"{round(h)} hours"
    if days < 100:
        return f"{days:.1f} Earth days".replace(".0 Earth", " Earth")
    return f"{round(days)} Earth days"


def compare(d):
    r = d / OUR_MOON
    if r > 1.05:
        return f"about {r:.1f} times as wide as our Moon".replace(".0 times", " times")
    if r > 0.95:
        return "about the same width as our Moon"
    if r >= 0.1:
        return f"about {round(r * 100)}% as wide as our Moon"
    return "tiny compared with our Moon, which is about 3,475 km across"


def main():
    lines = ["# Generated by tools/knowledge/gen/science_moons2.py. Do not edit by hand.",
             "# Sources: NASA/JPL Solar System Dynamics satellite parameters and NASA Science (public domain).",
             "# tag: science.space.moon"]
    for name, planet, d, who, year, note in MOONS:
        n = name.lower()
        a = f"{name}, a moon of {planet}, is about {d:,} km across, {compare(d)}."
        if note and "bigger" in note or note and "largest" in note or note and "half" in note or note and "lumpy" in note:
            a += " " + note
        lines.append(f"how big is {n} moon | how wide is the moon {n} | {n} moon size | what is the diameter of {n} => {a}")
        b = f"{name} was discovered by {who} in {year}."
        if who == "Galileo Galilei":
            b = f"{name} was discovered by Galileo Galilei in January 1610, along with Jupiter's other three big moons. Simon Marius may have spotted them around the same time."
        elif note and ("first" in note or "last" in note or "days after" in note):
            b += " " + note
        days, retro = ORBIT[name]
        c = f"{name} orbits {planet}{', a dwarf planet' if planet == 'Pluto' else ''}, going around once about every {period_text(days)}."
        if retro:
            c += f" It orbits backwards, opposite to the way {planet} spins, which suggests it was captured."
        if name == "Phobos":
            c += " That's faster than Mars spins, so Phobos rises in the west and sets in the east."
        if name == "Charon":
            c += " Pluto spins in the same time, so Pluto and Charon always show each other the same face."
        lines.append(f"what planet does {n} orbit | which planet is {n} a moon of | how long does {n} take to orbit => {c}")
        lines.append(f"who discovered {n} moon | when was the moon {n} discovered | {n} moon discovery => {b}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(lines) - 3} entries to {OUT}")


if __name__ == "__main__":
    main()
