#!/usr/bin/env python3
"""Writes data/science/gen_compare.txt: which planet is bigger, and which is hotter.

Data source: NASA Planetary Fact Sheet (https://nssdc.gsfc.nasa.gov/planetary/factsheet/),
mean radius and mean temperature. Public domain (NASA).

Run from the repo root:  python3 tools/knowledge/gen/science_compare.py
"""
import itertools
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "data", "science", "gen_compare.txt"))

# name, diameter in km (2 x mean radius, rounded), mean temperature in °C
PLANETS = [
    ("Mercury", 4879, 167),
    ("Venus", 12104, 464),
    ("Earth", 12742, 15),
    ("Mars", 6779, -65),
    ("Jupiter", 139820, -110),
    ("Saturn", 116460, -140),
    ("Uranus", 50724, -195),
    ("Neptune", 49244, -200),
]


def km(n):
    return f"{n:,} km"


def times(a, b):
    r = a / b
    if r < 1.15:
        return "only a little wider than"
    if r < 10:
        return f"about {r:.1f}".rstrip("0").rstrip(".") + " times as wide as"
    return f"about {round(r)} times as wide as"


def temp(c):
    return f"minus {abs(c)} °C" if c < 0 else f"{c} °C"


def main():
    lines = ["# Generated by tools/knowledge/gen/science_compare.py. Do not edit by hand.",
             "# Source: NASA Planetary Fact Sheet (public domain).",
             "# tag: science.space.planet"]
    for (a, da, ta), (b, db, tb) in itertools.combinations(PLANETS, 2):
        al, bl = a.lower(), b.lower()
        big, small = ((a, da), (b, db)) if da > db else ((b, db), (a, da))
        ans = f"{big[0]} is bigger. It's {km(big[1])} across, {times(big[1], small[1])} {small[0]} at {km(small[1])}."
        if a == "Venus" and b == "Earth":
            ans = "Earth is bigger, but only just. Earth is 12,742 km across and Venus is 12,104 km, so Venus is often called Earth's twin."
        if a == "Uranus" and b == "Neptune":
            ans = "Uranus is slightly bigger across, 50,724 km compared with Neptune's 49,244 km. But Neptune has more mass, so it's denser."
        lines.append(f"is {al} bigger than {bl} | which is bigger {al} or {bl} | which is bigger {bl} or {al} | is {bl} smaller than {al} => {ans}")

        hot, cold = ((a, ta), (b, tb)) if ta > tb else ((b, tb), (a, ta))
        ans = f"{hot[0]} is hotter. Its average temperature is about {temp(hot[1])}, while {cold[0]}'s is about {temp(cold[1])}."
        if {a, b} == {"Mercury", "Venus"}:
            ans = ("Venus is hotter, even though Mercury is closer to the Sun. Venus averages about 464 °C because its thick carbon dioxide "
                   "air traps heat, while Mercury averages about 167 °C and has almost no air.")
        lines.append(f"is {al} hotter than {bl} | which is hotter {al} or {bl} | which is hotter {bl} or {al} | is {bl} colder than {al} => {ans}")
    # Orbital periods in Earth years (NASA Planetary Fact Sheet).
    YEARS = [("Mercury", 0.2408), ("Venus", 0.6152), ("Mars", 1.8809), ("Jupiter", 11.862),
             ("Saturn", 29.457), ("Uranus", 84.011), ("Neptune", 164.79)]
    lines.append("# tag: science.space.planet")
    for name, yr in YEARS:
        n = name.lower()
        age12 = 12 / yr
        if age12 >= 10:
            a12 = f"about {round(age12)}"
        elif age12 >= 1:
            a12 = f"about {age12:.1f}"
        else:
            a12 = f"only about {age12:.2f}"
        ans = (f"Divide your age in Earth years by {yr:g}, because one {name} year lasts {yr:g} Earth years. "
               f"A 12-year-old would be {a12} {name} years old.")
        days = {"Mercury": 88, "Venus": 225, "Mars": 687}.get(name)
        if name == "Jupiter":
            ans = ans.replace("about 1.0 Jupiter years old", "just over 1 Jupiter year old")
        if name == "Neptune":
            ans += " Nobody has ever lived long enough to have even one birthday on Neptune."
        elif name == "Uranus":
            ans += " You'd need to live about 84 years to have your first birthday on Uranus."
        elif days:
            ans += f" You'd have a birthday on {name} every {days} Earth days."
        elif yr > 10:
            ans += f" You'd have a birthday on {name} only about every {round(yr)} Earth years."
        lines.append(f"how old would i be on {n} | my age on {n} | how many {n} years old am i | "
                     f"age in {n} years | how often would i have a birthday on {n} => {ans}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(lines) - 3} entries to {OUT}")


if __name__ == "__main__":
    main()
