"""Pokémon height and weight for Ace's knowledge pack.

Data: PokeAPI (BSD 3-Clause license), https://github.com/PokeAPI/pokeapi, data/v2/csv:
pokemon.csv (height in decimeters, weight in hectograms, default forms only) and pokemon_species_names.csv.
Writes data/games/gen_pokemon_size.txt. Run from the repo root:
    python3 tools/knowledge/gen/games_pokemon_size.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from games_common import Writer  # noqa: E402
from games_pokemon import EN, join, plain, rows  # noqa: E402


def height_text(dm):
    m = dm / 10
    inches = round(dm * 3.937)
    ft, inch = divmod(inches, 12)
    imp = f"{ft} ft {inch} in" if ft else f"{inch} in"
    return f"{m:g} m ({imp})"


def weight_text(hg):
    kg = hg / 10
    lb = round(kg * 2.20462, 1)
    return f"{kg:g} kg ({lb:g} lbs)"


def main():
    names = {r["pokemon_species_id"]: r["name"] for r in rows("pokemon_species_names") if r["local_language_id"] == EN}
    mons = [r for r in rows("pokemon") if r["is_default"] == "1" and int(r["species_id"]) <= 1025]
    f = "gen_pokemon_size.txt"
    w = Writer([f])
    for r in sorted(mons, key=lambda r: int(r["species_id"])):
        name = names[r["species_id"]]
        p = plain(name)
        dm, hg = int(r["height"]), int(r["weight"])
        w.add(f, "pokemon.size", [f"how tall is {p}", f"how much does {p} weigh", f"{p} height", f"{p} weight",
                                  f"how big is {p}", f"how heavy is {p}"],
              f"{name} is {height_text(dm)} tall and weighs {weight_text(hg)}, according to the Pokedex.")

    def by(key, rev):
        vals = sorted(mons, key=lambda r: int(r[key]), reverse=rev)
        top = int(vals[0][key])
        return [names[r["species_id"]] for r in vals if int(r[key]) == top], top

    tall, t = by("height", True)
    w.add(f, "pokemon.size", ["what is the tallest pokemon", "biggest pokemon by height", "which pokemon is the tallest"],
          f"{' and '.join(tall)} is the tallest Pokemon at {height_text(t)}, counting normal forms only.")
    heavy, h = by("weight", True)
    w.add(f, "pokemon.size", ["what is the heaviest pokemon", "which pokemon weighs the most", "heaviest pokemon ever"],
          f"{' and '.join(heavy)} share the record for heaviest Pokemon at {weight_text(h)}." if len(heavy) == 2 else
          f"The heaviest Pokemon is {', '.join(heavy)}, at {weight_text(h)}.")
    small, s = by("height", False)
    w.add(f, "pokemon.size", ["what is the smallest pokemon", "which pokemon is the shortest", "tiniest pokemon"],
          f"The shortest Pokemon are only {height_text(s)} tall. There are {len(small)} of them, including "
          f"{join(small[:4])}.")
    light, l_ = by("weight", False)
    w.add(f, "pokemon.size", ["what is the lightest pokemon", "which pokemon weighs the least", "lightest pokemon ever"],
          f"The lightest Pokemon weigh only {weight_text(l_)}. There are {len(light)} of them, including "
          f"{join(light[:4])}.")
    w.write(["Pokémon height and weight, generated by tools/knowledge/gen/games_pokemon_size.py",
             "Source: PokeAPI CSV data (BSD 3-Clause), default forms only."])


if __name__ == "__main__":
    main()
