def article_free(title):
    return title.lower().replace("!", "").replace(",", "").replace("'", "'")


def main():
    taken, keys = load_taken({os.path.abspath(OUT)})
    w = Writer(taken, keys)
    w.tag("school.english.books")
    for title, short, author, year, about in BOOKS:
        t = article_free(title)
        when = f", first published in {year}" if year else ""
        qs = [f"who wrote {t}", f"who is the author of {t}", f"{t} author", f"who wrote the book {t}"]
        if short and short != t:
            qs += [f"who wrote {short}", f"{short} author"]
        w.add(qs[:6], f"{title} was written by {author}{when}.")
        qs = [f"what is {t} about", f"{t} summary", f"what happens in {t}", f"{t} plot"]
        if short and short != t:
            qs += [f"what is {short} about", f"{short} book summary"]
        w.add(qs[:6], f"{title} is about {about}.")
    head = ("# Generated by tools/knowledge/gen/school_books.py (hand-written list of well-known books, no spoilers).\n"
            "# Do not edit by hand; change the generator and run it again.\n")
    n = w.write(OUT, head)
    print(f"wrote {n} entries to gen_books.txt")


if __name__ == "__main__":
    main()
