text = input("Word for the banner: ").upper() or "STORM"
fill = input("Character to draw with (Enter for #): ")[:1] or "#"

for row in range(5):
    line = "  ".join(FONT.get(ch, FONT[" "])[row] for ch in text)
    print(line.replace("#", fill))
